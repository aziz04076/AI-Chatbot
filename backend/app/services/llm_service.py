import asyncio
import time
import json
import re
from typing import AsyncGenerator, List, Dict, Any, Optional
import httpx
from app.config import settings
from app.core.circuit_breaker import llm_circuit_breaker
import logging

logger = logging.getLogger("NexusAI-LLM")

class LLMService:
    """
    Unified streaming inference service supporting:
    - vLLM high-throughput server
    - OpenAI / Groq / HuggingFace endpoints with Circuit Breaker and Exponential Backoff
    - Realistic offline simulated domain inference for zero-setup execution and fallback
    """
    def __init__(self):
        self.mode = settings.INFERENCE_MODE

    async def _stream_remote(
        self,
        messages: List[Dict[str, str]],
        model_name: str,
        temperature: float
    ) -> AsyncGenerator[str, None]:
        """Calls external OpenAI / vLLM / Groq streaming endpoint."""
        headers = {"Authorization": f"Bearer {settings.LLM_API_KEY}"}
        payload = {
            "model": model_name,
            "messages": messages,
            "temperature": temperature,
            "stream": True
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            async with client.stream(
                "POST",
                f"{settings.LLM_API_BASE}/chat/completions",
                json=payload,
                headers=headers
            ) as response:
                if response.status_code >= 400:
                    raise httpx.HTTPStatusError(
                        f"External LLM returned HTTP {response.status_code}",
                        request=response.request,
                        response=response
                    )
                async for line in response.aiter_lines():
                    if line.startswith("data: ") and line != "data: [DONE]":
                        try:
                            data = json.loads(line[6:])
                            delta = data["choices"][0].get("delta", {}).get("content", "")
                            if delta:
                                yield delta
                        except Exception:
                            continue

    async def _stream_mock(
        self,
        messages: List[Dict[str, str]],
        context_chunks: Optional[List[str]] = None
    ) -> AsyncGenerator[str, None]:
        """High-Fidelity Domain Simulation Fallback Engine."""
        user_query = ""
        for m in reversed(messages):
            if m.get("role") == "user":
                user_query = m.get("content", "")
                break

        tokens = self._generate_domain_tokens(user_query, context_chunks)
        for token in tokens:
            yield token
            await asyncio.sleep(0.022)

    async def stream_chat_completion(
        self,
        messages: List[Dict[str, str]],
        model_name: str = "nexus-llama3-8b-v1",
        temperature: float = 0.7,
        context_chunks: Optional[List[str]] = None
    ) -> AsyncGenerator[str, None]:
        """
        Yields tokens one by one as they are generated by the model.
        Guarded with Circuit Breaker and Exponential Backoff.
        """
        # If external OpenAI/vLLM endpoint configured and mode != 'mock'
        if self.mode in ["vllm", "openai", "groq"] and settings.LLM_API_BASE:
            async for token in llm_circuit_breaker.execute_stream(
                lambda: self._stream_remote(messages, model_name, temperature),
                lambda: self._stream_mock(messages, context_chunks)
            ):
                yield token
            return

        # Default local/mock domain simulation engine
        async for token in self._stream_mock(messages, context_chunks):
            yield token

